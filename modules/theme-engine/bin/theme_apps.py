#!/usr/bin/env python3
from __future__ import annotations

import configparser
import json
import os
from pathlib import Path
from typing import Any

HOME = Path.home()
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config"))


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".theme-engine.tmp")
    temporary.write_text(text, encoding="utf-8")
    os.replace(temporary, path)


def _ensure_line(path: Path, line: str) -> None:
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    if line in text:
        return
    prefix = "" if not text else ("" if text.endswith("\n") else "\n")
    _atomic_write(path, text + prefix + line + "\n")


def _firefox_roots() -> list[Path]:
    candidates = [
        HOME / ".mozilla/firefox",
        HOME / ".librewolf",
        HOME / ".floorp",
        HOME / ".waterfox",
        HOME / ".mozilla/icecat",
        HOME / ".var/app/org.mozilla.firefox/.mozilla/firefox",
        HOME / ".var/app/io.gitlab.librewolf-community/.librewolf",
        HOME / ".var/app/one.ablaze.floorp/.floorp",
    ]
    # Zen has used more than one config layout over time; support both common roots.
    candidates.extend([HOME / ".zen", HOME / ".config/zen"])
    return candidates


def _profiles_from_ini(root: Path) -> list[Path]:
    ini = root / "profiles.ini"
    if not ini.is_file():
        return []
    parser = configparser.RawConfigParser()
    try:
        parser.read(ini, encoding="utf-8")
    except (configparser.Error, OSError):
        return []
    profiles: list[Path] = []
    for section in parser.sections():
        if not section.lower().startswith("profile"):
            continue
        raw_path = parser.get(section, "Path", fallback="").strip()
        if not raw_path:
            continue
        relative = parser.getboolean(section, "IsRelative", fallback=True)
        profile = (root / raw_path) if relative else Path(raw_path).expanduser()
        if profile.is_dir():
            profiles.append(profile)
    return profiles


def firefox_profiles() -> list[Path]:
    found: set[Path] = set()
    for root in _firefox_roots():
        if not root.is_dir():
            continue
        found.update(path.resolve() for path in _profiles_from_ini(root))
        # Fallback for forks that omit profiles.ini or use a non-Mozilla wrapper.
        for child in root.iterdir():
            if child.is_dir() and (
                "default" in child.name.lower()
                or (child / "prefs.js").is_file()
                or (child / "places.sqlite").is_file()
            ):
                found.add(child.resolve())
    return sorted(found)


def _firefox_css(theme: dict[str, Any]) -> str:
    r = theme["roles"]
    return f'''/* AUTO-GENERATED by Arch-WM `theme`; edit your own userChrome.css instead. */
:root {{
  --toolbar-bgcolor: {r['bg']} !important;
  --toolbar-color: {r['text']} !important;
  --lwt-accent-color: {r['bg']} !important;
  --lwt-text-color: {r['text']} !important;
  --toolbar-field-background-color: {r['bg_alt']} !important;
  --toolbar-field-color: {r['text']} !important;
  --toolbar-field-focus-background-color: {r['surface_1']} !important;
  --toolbar-field-focus-color: {r['text']} !important;
}}
#navigator-toolbox,
#nav-bar,
#TabsToolbar {{ background-color: {r['bg']} !important; color: {r['text']} !important; }}
.tab-background[selected] {{ background-color: {r['bg_alt']} !important; }}
.tabbrowser-tab {{ color: {r['text_dim']} !important; }}
.tabbrowser-tab[selected] {{ color: {r['accent']} !important; }}
#urlbar-background {{ background-color: {r['bg_alt']} !important; }}
#urlbar {{ color: {r['text']} !important; }}
:root {{ --focus-outline-color: {r['focus']} !important; }}
'''


def apply_firefox(theme: dict[str, Any]) -> tuple[int, list[str]]:
    profiles = firefox_profiles()
    for profile in profiles:
        chrome = profile / "chrome"
        chrome.mkdir(parents=True, exist_ok=True)
        _atomic_write(chrome / "theme-engine.css", _firefox_css(theme))
        # Own one import only; preserve every other user customization.
        _ensure_line(chrome / "userChrome.css", '@import url("theme-engine.css");')
        _ensure_line(
            profile / "user.js",
            'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);',
        )
    return len(profiles), [str(path) for path in profiles]


def _obsidian_registry_files() -> list[Path]:
    return [
        CONFIG / "obsidian/obsidian.json",
        HOME / ".var/app/md.obsidian.Obsidian/config/obsidian/obsidian.json",
    ]


def obsidian_vaults() -> list[Path]:
    vaults: set[Path] = set()
    for registry in _obsidian_registry_files():
        if not registry.is_file():
            continue
        try:
            data = json.loads(registry.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        raw_vaults = data.get("vaults", {}) if isinstance(data, dict) else {}
        if not isinstance(raw_vaults, dict):
            continue
        for entry in raw_vaults.values():
            if not isinstance(entry, dict):
                continue
            raw_path = entry.get("path")
            if isinstance(raw_path, str):
                vault = Path(raw_path).expanduser()
                if (vault / ".obsidian").is_dir():
                    vaults.add(vault.resolve())
    return sorted(vaults)


def _obsidian_css(theme: dict[str, Any]) -> str:
    r = theme["roles"]
    return f'''/* AUTO-GENERATED by Arch-WM `theme`. */
body {{
  --background-primary: {r['bg']};
  --background-primary-alt: {r['bg_alt']};
  --background-secondary: {r['surface_1']};
  --background-secondary-alt: {r['surface_2']};
  --text-normal: {r['text']};
  --text-muted: {r['text_dim']};
  --text-accent: {r['accent']};
  --text-accent-hover: {r['accent2']};
  --interactive-accent: {r['accent']};
  --interactive-accent-hover: {r['accent2']};
  --interactive-normal: {r['surface_1']};
  --interactive-hover: {r['hover']};
  --background-modifier-border: {r['border_subtle']};
  --background-modifier-border-focus: {r['border_strong']};
  --text-selection: {r['accent']}40;
  --text-error: {r['urgent']};
}}
'''


def apply_obsidian(theme: dict[str, Any]) -> tuple[int, list[str]]:
    vaults = obsidian_vaults()
    for vault in vaults:
        config_dir = vault / ".obsidian"
        snippet_dir = config_dir / "snippets"
        snippet_dir.mkdir(parents=True, exist_ok=True)
        _atomic_write(snippet_dir / "theme-engine.css", _obsidian_css(theme))
        appearance = config_dir / "appearance.json"
        try:
            data = json.loads(appearance.read_text(encoding="utf-8")) if appearance.is_file() else {}
        except (OSError, json.JSONDecodeError):
            # Never replace a malformed user settings file.
            continue
        if not isinstance(data, dict):
            continue
        snippets = data.get("enabledCssSnippets", [])
        if not isinstance(snippets, list):
            snippets = []
        if "theme-engine" not in snippets:
            snippets.append("theme-engine")
        data["enabledCssSnippets"] = snippets
        _atomic_write(appearance, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    return len(vaults), [str(path) for path in vaults]


def detect() -> dict[str, list[str]]:
    return {
        "firefox": [str(path) for path in firefox_profiles()],
        "obsidian": [str(path) for path in obsidian_vaults()],
    }


def apply_detected(theme: dict[str, Any]) -> list[str]:
    messages: list[str] = []
    firefox_count, _ = apply_firefox(theme)
    if firefox_count:
        messages.append(f"Firefox-family: themed {firefox_count} profile(s); restart browser")
    obsidian_count, _ = apply_obsidian(theme)
    if obsidian_count:
        messages.append(f"Obsidian: themed {obsidian_count} vault(s); hot reload")
    return messages
