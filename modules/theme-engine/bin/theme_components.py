@register("prompt", "Prompt", "Starship prompt layout, separators, modules, and status roles")
def apply_prompt(theme: dict[str, Any]) -> list[Path]:
    """Render the real starship.toml that .zshrc points STARSHIP_CONFIG at.

    Earlier versions wrote a dead starship-studio.json that nothing read; the
    actual prompt stayed on the legacy generator's minimal config. This plugin
    now renders the full two-line prompt from theme_starship with the theme
    palette and the Prompt room's toggles.
    """
    theme = ensure_theme_schema(theme)
    c = theme["components"]["prompt"]
    roles = resolve_roles(theme.get("roles", {}))
    from theme_starship import DEFAULT as SHIP_DEFAULTS
    from theme_starship import render as render_starship
    settings = dict(SHIP_DEFAULTS)
    settings["duration_enabled"] = bool(c.get("show_duration", True))
    settings["jobs_enabled"] = bool(c.get("show_jobs", True))
    settings["battery_enabled"] = bool(c.get("show_battery", False))
    settings["memory_enabled"] = bool(c.get("show_memory", False))
    settings["time_enabled"] = bool(c.get("show_time", False))
    separator = str(c.get("separator", "powerline"))
    settings.update(SEPARATOR_GLYPHS.get(separator, SEPARATOR_GLYPHS["powerline"]))
    settings["one_line"] = str(c.get("layout", "two_line")) == "one_line"
    settings["directory_color"] = role_color(theme, str(c.get("directory_role", "accent")))
    settings["git_color"] = role_color(theme, str(c.get("git_role", "accent2")))
    settings["status_color"] = role_color(theme, str(c.get("status_role", "urgent")))
    path = CFG / "theme-engine" / "generated" / "starship.toml"
    atomic_text(path, render_starship(roles, settings))
    return [path]


